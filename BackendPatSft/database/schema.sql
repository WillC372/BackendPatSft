-- ============================================================================
-- PoolGuard - Database Schema (MySQL 8+ / MariaDB 10.4+)
-- Caso de estudio: Patrones de Software
-- ============================================================================

CREATE DATABASE IF NOT EXISTS poolguard CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE poolguard;

-- --------------------------------------------------------------------------
-- Users (passwords are ALWAYS stored as PBKDF2-SHA256 hashes, never plain)
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          ENUM('ADMIN', 'OPERATOR') NOT NULL,
    full_name     VARCHAR(120),
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- --------------------------------------------------------------------------
-- Pools
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pools (
    id                    INT AUTO_INCREMENT PRIMARY KEY,
    name                  VARCHAR(100) NOT NULL,
    volume_m3             DECIMAL(10, 2) NOT NULL,
    target_ph_min         DECIMAL(4, 2) DEFAULT 7.2,
    target_ph_max         DECIMAL(4, 2) DEFAULT 7.6,
    target_chlorine_min   DECIMAL(4, 2) DEFAULT 1.0,
    target_chlorine_max   DECIMAL(4, 2) DEFAULT 3.0
);

-- --------------------------------------------------------------------------
-- Sensor readings (time-series data from the Bluetooth meter)
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sensor_readings (
    id             BIGINT AUTO_INCREMENT PRIMARY KEY,
    pool_id        INT NOT NULL,
    ph             DECIMAL(4, 2) NOT NULL,
    temperature_c  DECIMAL(4, 2) NOT NULL,
    chlorine_ppm   DECIMAL(4, 2) NOT NULL,
    bather_load    INT DEFAULT 0,
    recorded_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_readings_time (recorded_at),
    FOREIGN KEY (pool_id) REFERENCES pools (id)
);

-- --------------------------------------------------------------------------
-- Alerts (push / voice / visual) generated by the system
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS alerts (
    id          BIGINT AUTO_INCREMENT PRIMARY KEY,
    pool_id     INT NOT NULL,
    type        VARCHAR(30)  NOT NULL,   -- PUSH | VOICE | VISUAL
    severity    VARCHAR(20)  NOT NULL,   -- INFO | WARNING | CRITICAL
    message_es  VARCHAR(500) NOT NULL,   -- message shown/spoken in Spanish
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (pool_id) REFERENCES pools (id)
);

-- --------------------------------------------------------------------------
-- Maintenance records (chemical treatments performed on the pool)
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS maintenance_records (
    id            BIGINT AUTO_INCREMENT PRIMARY KEY,
    pool_id       INT NOT NULL,
    performed_by  VARCHAR(50)  NOT NULL,
    description   VARCHAR(500),
    chemical_used VARCHAR(100),
    quantity      DECIMAL(10, 2),
    unit          VARCHAR(10),
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (pool_id) REFERENCES pools (id)
);

-- --------------------------------------------------------------------------
-- Immutable audit log (Command pattern)
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS audit_log (
    id         BIGINT AUTO_INCREMENT PRIMARY KEY,
    username   VARCHAR(50)  NOT NULL,
    action     VARCHAR(100) NOT NULL,
    details    VARCHAR(1000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- --------------------------------------------------------------------------
-- Safety thresholds (single row, id = 1)
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS thresholds (
    id                     INT PRIMARY KEY DEFAULT 1,
    ph_optimal_min         DECIMAL(4, 2) DEFAULT 7.2,
    ph_optimal_max         DECIMAL(4, 2) DEFAULT 7.6,
    ph_caution_min         DECIMAL(4, 2) DEFAULT 7.0,
    ph_caution_max         DECIMAL(4, 2) DEFAULT 7.8,
    ph_critical_min        DECIMAL(4, 2) DEFAULT 6.8,
    ph_critical_max        DECIMAL(4, 2) DEFAULT 8.0,
    chlorine_optimal_min   DECIMAL(4, 2) DEFAULT 1.0,
    chlorine_optimal_max   DECIMAL(4, 2) DEFAULT 3.0,
    chlorine_caution_min   DECIMAL(4, 2) DEFAULT 0.7,
    chlorine_caution_max   DECIMAL(4, 2) DEFAULT 3.5,
    chlorine_critical_min  DECIMAL(4, 2) DEFAULT 0.3,
    chlorine_critical_max  DECIMAL(4, 2) DEFAULT 5.0
);

