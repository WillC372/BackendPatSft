-- Treatments applied to a place (chemicals, water changes, filter cleaning), the history of meter calibrations,
-- reminders, and the devices where a person accepted notifications (Web Push).

CREATE TABLE treatments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id    BIGINT        NOT NULL REFERENCES places (id) ON DELETE CASCADE,
    user_id     BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    applied_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    product     VARCHAR(30)   NOT NULL,
    amount      DOUBLE PRECISION,
    unit        VARCHAR(10),
    note        VARCHAR(300),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_treatment_amount CHECK (amount IS NULL OR (amount > 0 AND amount <= 1000000))
);
CREATE INDEX ix_treatments_place_time ON treatments (place_id, applied_at DESC);

CREATE TABLE calibrations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    device_name  VARCHAR(80)   NOT NULL,
    protocol     VARCHAR(30),
    point        VARCHAR(10)   NOT NULL,
    buffer_value DOUBLE PRECISION,
    reading      DOUBLE PRECISION,
    response     VARCHAR(200),
    success      BOOLEAN       NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_calibrations_user_time ON calibrations (user_id, created_at DESC);

CREATE TABLE reminders (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    place_id          BIGINT        REFERENCES places (id) ON DELETE CASCADE,
    kind              VARCHAR(20)   NOT NULL,
    title             VARCHAR(80)   NOT NULL,
    every_days        INT           NOT NULL,
    next_due          TIMESTAMP WITH TIME ZONE NOT NULL,
    by_email          BOOLEAN       NOT NULL,
    by_push           BOOLEAN       NOT NULL,
    active            BOOLEAN       NOT NULL,
    last_notified_at  TIMESTAMP WITH TIME ZONE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_reminder_every CHECK (every_days BETWEEN 1 AND 365)
);
CREATE INDEX ix_reminders_due ON reminders (active, next_due);

CREATE TABLE push_subscriptions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    endpoint      VARCHAR(600)  NOT NULL UNIQUE,
    p256dh        VARCHAR(200)  NOT NULL,
    auth          VARCHAR(100)  NOT NULL,
    device_label  VARCHAR(120),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    last_sent_at  TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_push_user ON push_subscriptions (user_id);

-- Keys the server creates for itself the first time (the Web Push key pair), so no setting is needed.
CREATE TABLE app_keys (
    key_name    VARCHAR(40)   PRIMARY KEY,
    key_value   VARCHAR(2000) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Alerts of measurements out of range can also arrive by email.
ALTER TABLE user_settings ADD COLUMN email_alerts BOOLEAN NOT NULL DEFAULT TRUE;

-- Any language of the interface (codes like "es", "pt-BR" or "zh-Hans").
ALTER TABLE user_settings ALTER COLUMN language SET DATA TYPE VARCHAR(12);
