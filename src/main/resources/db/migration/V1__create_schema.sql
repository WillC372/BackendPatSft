CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(160)  NOT NULL UNIQUE,
    full_name       VARCHAR(120)  NOT NULL,
    password_hash   VARCHAR(255)  NOT NULL,
    role            VARCHAR(20)   NOT NULL,
    plan            VARCHAR(20)   NOT NULL,
    token_version   INT           NOT NULL DEFAULT 0,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_users_plan CHECK (plan IN ('FREE', 'PREMIUM'))
);

CREATE TABLE water_profiles (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        BIGINT REFERENCES users (id) ON DELETE CASCADE,
    name            VARCHAR(80)   NOT NULL,
    type            VARCHAR(30)   NOT NULL,
    ideal_min       DOUBLE PRECISION NOT NULL,
    ideal_max       DOUBLE PRECISION NOT NULL,
    caution_min     DOUBLE PRECISION NOT NULL,
    caution_max     DOUBLE PRECISION NOT NULL,
    description     VARCHAR(500)  NOT NULL,
    source          VARCHAR(300)  NOT NULL,
    system_profile  BOOLEAN       NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_profile_bounds CHECK (caution_min >= 0 AND caution_max <= 14),
    CONSTRAINT ck_profile_order CHECK (caution_min <= ideal_min AND ideal_min < ideal_max AND ideal_max <= caution_max)
);
CREATE INDEX ix_profiles_owner ON water_profiles (owner_id);

CREATE TABLE user_settings (
    user_id                BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    active_profile_id      BIGINT REFERENCES water_profiles (id) ON DELETE SET NULL,
    theme                  VARCHAR(10) NOT NULL,
    notifications_enabled  BOOLEAN     NOT NULL,
    auto_save              BOOLEAN     NOT NULL,
    language               VARCHAR(5)  NOT NULL,
    CONSTRAINT ck_settings_theme CHECK (theme IN ('AUTO', 'LIGHT', 'DARK'))
);

CREATE TABLE devices (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id           BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name               VARCHAR(80)  NOT NULL,
    protocol           VARCHAR(30)  NOT NULL,
    port               VARCHAR(160) NOT NULL,
    simulated          BOOLEAN      NOT NULL,
    last_connected_at  TIMESTAMP WITH TIME ZONE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_devices_owner_port UNIQUE (owner_id, port)
);

CREATE TABLE measurements (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    device_id          BIGINT       REFERENCES devices (id) ON DELETE SET NULL,
    profile_id         BIGINT       NOT NULL REFERENCES water_profiles (id),
    ph                 DOUBLE PRECISION NOT NULL,
    temperature_c      DOUBLE PRECISION,
    measured_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    source             VARCHAR(15)  NOT NULL,
    nature             VARCHAR(15)  NOT NULL,
    status             VARCHAR(15)  NOT NULL,
    validation_status  VARCHAR(15)  NOT NULL,
    validation_notes   VARCHAR(500),
    note               VARCHAR(300),
    CONSTRAINT ck_measurement_ph CHECK (ph >= 0 AND ph <= 14),
    CONSTRAINT ck_measurement_source CHECK (source IN ('REAL', 'SIMULATED', 'MANUAL'))
);
CREATE INDEX ix_measurements_user_time ON measurements (user_id, measured_at DESC);

CREATE TABLE alerts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    measurement_id  BIGINT       REFERENCES measurements (id) ON DELETE SET NULL,
    severity        VARCHAR(15)  NOT NULL,
    title           VARCHAR(120) NOT NULL,
    message         VARCHAR(600) NOT NULL,
    is_read         BOOLEAN      NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_alerts_user_time ON alerts (user_id, created_at DESC);

CREATE TABLE password_reset_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64) NOT NULL UNIQUE,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at     TIMESTAMP WITH TIME ZONE
);

CREATE TABLE ai_usage (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    purpose        VARCHAR(40) NOT NULL,
    model          VARCHAR(60) NOT NULL,
    input_tokens   BIGINT      NOT NULL,
    output_tokens  BIGINT      NOT NULL,
    cached         BOOLEAN     NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_ai_usage_user_time ON ai_usage (user_id, created_at);

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT REFERENCES users (id) ON DELETE CASCADE,
    action      VARCHAR(60)  NOT NULL,
    detail      VARCHAR(500) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_audit_user_time ON audit_log (user_id, created_at DESC);
