-- Official public pH data: monitoring stations of the U.S. Geological Survey (USGS) and their readings, imported from
-- the USGS Water Data OGC API. Separate from the users' measurements: they are reference data, not the user's water.
CREATE TABLE reference_stations (
    id              VARCHAR(40) PRIMARY KEY,
    agency          VARCHAR(20)  NOT NULL,
    name            VARCHAR(200),
    state           VARCHAR(60),
    site_type       VARCHAR(60),
    latitude        DOUBLE PRECISION,
    longitude       DOUBLE PRECISION,
    last_ph         NUMERIC(4, 2),
    last_time       TIMESTAMP WITH TIME ZONE,
    approval_status VARCHAR(30),
    featured        BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_reference_stations_time ON reference_stations (last_time DESC);

CREATE TABLE reference_readings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id      VARCHAR(40) NOT NULL REFERENCES reference_stations (id) ON DELETE CASCADE,
    measured_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    ph              NUMERIC(4, 2) NOT NULL,
    approval_status VARCHAR(30),
    CONSTRAINT uq_reference_reading UNIQUE (station_id, measured_at)
);

-- Each import is recorded so the screen can say when the data was last refreshed and whether it worked.
CREATE TABLE reference_imports (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    stations    INT NOT NULL DEFAULT 0,
    readings    INT NOT NULL DEFAULT 0,
    success     BOOLEAN NOT NULL DEFAULT FALSE,
    message     VARCHAR(300)
);
