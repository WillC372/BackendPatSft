-- Memoria del asistente: conversaciones y mensajes por usuario. Se borran con la cuenta.
CREATE TABLE chat_conversations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title       VARCHAR(120)  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_chat_conversations_user ON chat_conversations (user_id, updated_at DESC);

CREATE TABLE chat_messages (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  BIGINT        NOT NULL REFERENCES chat_conversations (id) ON DELETE CASCADE,
    role             VARCHAR(10)   NOT NULL,
    content          VARCHAR(6000) NOT NULL,
    model            VARCHAR(80),
    citations        VARCHAR(400),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_chat_role CHECK (role IN ('USER', 'ASSISTANT'))
);
CREATE INDEX ix_chat_messages_conversation ON chat_messages (conversation_id, id);
