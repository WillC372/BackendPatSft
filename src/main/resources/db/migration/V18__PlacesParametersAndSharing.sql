-- Places: each person can follow several bodies of water (a pool, an aquarium, a tank...). Every measurement belongs
-- to a place, and a place can be shared with other accounts through a code (to see it or also to measure in it).

CREATE TABLE places (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name            VARCHAR(80)   NOT NULL,
    kind            VARCHAR(20)   NOT NULL,
    volume_liters   DOUBLE PRECISION,
    profile_id      BIGINT        NOT NULL REFERENCES water_profiles (id),
    share_code      VARCHAR(12)   UNIQUE,
    share_role      VARCHAR(10),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_place_kind CHECK (kind IN ('GENERAL', 'POOL', 'SPA', 'AQUARIUM', 'POND', 'DRINKING', 'IRRIGATION', 'HYDROPONICS', 'OTHER')),
    CONSTRAINT ck_place_volume CHECK (volume_liters IS NULL OR (volume_liters > 0 AND volume_liters <= 100000000)),
    CONSTRAINT ck_place_share_role CHECK (share_role IS NULL OR share_role IN ('VIEWER', 'EDITOR'))
);
CREATE INDEX ix_places_owner ON places (owner_id);

CREATE TABLE place_members (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id    BIGINT       NOT NULL REFERENCES places (id) ON DELETE CASCADE,
    user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role        VARCHAR(10)  NOT NULL,
    joined_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_place_member UNIQUE (place_id, user_id),
    CONSTRAINT ck_place_member_role CHECK (role IN ('VIEWER', 'EDITOR'))
);
CREATE INDEX ix_place_members_user ON place_members (user_id);

-- Every existing account gets one place, "Mi agua", with its active profile; its measurements move there.
INSERT INTO places (owner_id, name, kind, volume_liters, profile_id, created_at)
SELECT u.id, 'Mi agua', 'GENERAL', NULL,
       COALESCE((SELECT s.active_profile_id FROM user_settings s WHERE s.user_id = u.id),
                (SELECT MIN(p.id) FROM water_profiles p WHERE p.system_profile = TRUE AND p.type = 'GENERAL')),
       CURRENT_TIMESTAMP
FROM users u;

ALTER TABLE measurements ADD COLUMN place_id BIGINT REFERENCES places (id) ON DELETE CASCADE;
UPDATE measurements SET place_id = (SELECT MIN(p.id) FROM places p WHERE p.owner_id = measurements.user_id);
ALTER TABLE measurements ALTER COLUMN place_id SET NOT NULL;
CREATE INDEX ix_measurements_place_time ON measurements (place_id, measured_at DESC);

-- Other water parameters, all optional (mg/L = ppm; alkalinity and hardness as CaCO3).
ALTER TABLE measurements ADD COLUMN free_chlorine DOUBLE PRECISION;
ALTER TABLE measurements ADD COLUMN total_alkalinity DOUBLE PRECISION;
ALTER TABLE measurements ADD COLUMN calcium_hardness DOUBLE PRECISION;
ALTER TABLE measurements ADD COLUMN cyanuric_acid DOUBLE PRECISION;

ALTER TABLE user_settings ADD COLUMN active_place_id BIGINT REFERENCES places (id) ON DELETE SET NULL;
UPDATE user_settings SET active_place_id = (SELECT MIN(p.id) FROM places p WHERE p.owner_id = user_settings.user_id);
