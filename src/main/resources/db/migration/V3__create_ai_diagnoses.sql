CREATE TABLE ai_diagnoses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    source        VARCHAR(10)  NOT NULL,
    provider      VARCHAR(60),
    model         VARCHAR(80),
    risk_level    VARCHAR(15)  NOT NULL,
    payload       VARCHAR(20000) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_diagnosis_source CHECK (source IN ('AI', 'RULES')),
    CONSTRAINT ck_diagnosis_risk CHECK (risk_level IN ('LOW', 'MODERATE', 'HIGH', 'CRITICAL'))
);
CREATE INDEX ix_ai_diagnoses_user_time ON ai_diagnoses (user_id, created_at DESC);
