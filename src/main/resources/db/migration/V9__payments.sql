-- Pagos con la pasarela (PayU). Nunca se guardan datos de tarjeta: el pago ocurre en la página de PayU.
CREATE TABLE payments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    provider            VARCHAR(20)   NOT NULL,
    reference_code      VARCHAR(64)   NOT NULL UNIQUE,
    amount              NUMERIC(12, 2) NOT NULL,
    currency            VARCHAR(3)    NOT NULL,
    period_days         INT           NOT NULL,
    status              VARCHAR(12)   NOT NULL,
    test_mode           BOOLEAN       NOT NULL,
    provider_order_id   VARCHAR(40),
    provider_tx_id      VARCHAR(64),
    provider_state      VARCHAR(40),
    payment_method      VARCHAR(40),
    premium_until       TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_payment_status CHECK (status IN ('PENDING', 'APPROVED', 'DECLINED', 'ERROR', 'EXPIRED'))
);
CREATE INDEX ix_payments_user_time ON payments (user_id, created_at DESC);
