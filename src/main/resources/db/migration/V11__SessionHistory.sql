-- Session history: each login opens a session that groups everything the user does until logout.
CREATE TABLE user_sessions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    started_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    last_activity_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at         TIMESTAMP WITH TIME ZONE,
    end_reason       VARCHAR(30),
    remember_me      BOOLEAN NOT NULL DEFAULT FALSE,
    client           VARCHAR(80)
);
CREATE INDEX ix_sessions_user_start ON user_sessions (user_id, started_at DESC);

ALTER TABLE audit_log ADD COLUMN session_id BIGINT REFERENCES user_sessions (id) ON DELETE SET NULL;
CREATE INDEX ix_audit_session ON audit_log (session_id, created_at);
