-- Premium per period: expiry date (NULL = assigned by an administrator, no expiry)
-- and the expiry for which the reminder was already sent.
ALTER TABLE users ADD COLUMN premium_until TIMESTAMP WITH TIME ZONE;
ALTER TABLE users ADD COLUMN premium_reminder_for TIMESTAMP WITH TIME ZONE;

-- Payments through the gateway (PayU). Card data is never stored: the payment happens on the PayU page.
CREATE TABLE payments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    provider            VARCHAR(20)   NOT NULL,
    reference_code      VARCHAR(64)   NOT NULL UNIQUE,
    amount              NUMERIC(12, 2) NOT NULL,
    currency            VARCHAR(3)    NOT NULL,
    period_days         INT           NOT NULL,
    status              VARCHAR(12)   NOT NULL,
    test_mode           BOOLEAN       NOT NULL,
    provider_order_id   VARCHAR(40),
    provider_tx_id      VARCHAR(64),
    provider_state      VARCHAR(40),
    payment_method      VARCHAR(40),
    premium_until       TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_payment_status CHECK (status IN ('PENDING', 'APPROVED', 'DECLINED', 'ERROR', 'EXPIRED'))
);
CREATE INDEX ix_payments_user_time ON payments (user_id, created_at DESC);
